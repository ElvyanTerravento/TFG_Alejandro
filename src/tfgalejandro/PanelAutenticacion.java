    private void bLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bLoginActionPerformed
        // Leer todos los JSON en USERS_DIR y buscar coincidencia user/password
        String user = textoUsuario.getText() != null ? textoUsuario.getText().trim() : "";
    String pass = "";
    try { pass = new String(textoClave.getPassword()).trim(); } catch (Exception ignored) {}
        if (user.isEmpty() || pass.isEmpty()) return;

        File dir = new File(USERS_DIR);
        if (!dir.exists() || !dir.isDirectory()) return;

        boolean matched = false;
        Pattern uPat = Pattern.compile("\"username\"\\s*:\\s*\"([^\"]+)\"", Pattern.CASE_INSENSITIVE);
        Pattern pPat = Pattern.compile("\"password\"\\s*:\\s*\"([^\"]+)\"", Pattern.CASE_INSENSITIVE);

        for (File f : dir.listFiles((d, name) -> name.toLowerCase().endsWith(".json"))) {
            try (BufferedReader br = new BufferedReader(new FileReader(f, StandardCharsets.UTF_8))) {
                StringBuilder sb = new StringBuilder();
                String line;
                while ((line = br.readLine()) != null) sb.append(line).append('\n');
                String content = sb.toString();
                Matcher mu = uPat.matcher(content);
                Matcher mp = pPat.matcher(content);
                String fu = mu.find() ? mu.group(1) : null;
                String fp = mp.find() ? mp.group(1) : null;
                if (fu != null && fp != null) {
                    if (fu.equals(user) && fp.equals(pass)) { matched = true; break; }
                }
            } catch (Exception ignore) {}
        }

        if (matched) {
            // Resaltar en verde ambos campos durante 2s y después limpiar
            SwingUtilities.invokeLater(() -> {
                textoUsuario.setBackground(Color.GREEN);
                textoClave.setBackground(Color.GREEN);
            });
            Timer t = new Timer(2000, new ActionListener() {
                @Override
                public void actionPerformed(ActionEvent e) {
                    SwingUtilities.invokeLater(() -> {
                        textoUsuario.setBackground(usuarioBaseBg);
                        textoClave.setBackground(claveBaseBg);
                        textoUsuario.setText("");
                        textoClave.setText("");
                    });
                    ((Timer)e.getSource()).stop();
                }
            });
            t.setRepeats(false);
            t.start();
        } else {
            // Fallo: resaltar contraseña en rojo 2s y limpiar contraseña
            SwingUtilities.invokeLater(() -> textoClave.setBackground(Color.RED));
            Timer t2 = new Timer(2000, new ActionListener() {
                @Override
                public void actionPerformed(ActionEvent e) {
                    SwingUtilities.invokeLater(() -> {
                        textoClave.setBackground(claveBaseBg);
                        textoClave.setText("");
                    });
                    ((Timer)e.getSource()).stop();
                }
            });
            t2.setRepeats(false);
            t2.start();
        }
    }//GEN-LAST:event_bLoginActionPerformed


