    public void addTextoClave(String texto){
        if (texto == null) return;
        String t = texto.trim();
        if (t.isEmpty()) return;

        // Manejar tokens especiales
        if ("DEL".equalsIgnoreCase(t)) {
            deleteLast();
            return;
        }
        if ("SPACE".equalsIgnoreCase(t)) {
            String curr = new String(textoClave.getPassword());
            textoClave.setText(curr.concat(" "));
            return;
        }
        if ("NOTHING".equalsIgnoreCase(t)) {
            return; // no escribir nada
        }

        String curr = new String(textoClave.getPassword());
        textoClave.setText(curr.concat(t));
    }
    
    public void deleteLast(){
    String current = new String(textoClave.getPassword());
        if (current != null && !current.isEmpty()) {
            textoClave.setText(current.substring(0, current.length()-1));
        }
    }
    
    public void clearTextoSigno(){
        textoClave.setText("");
    }

