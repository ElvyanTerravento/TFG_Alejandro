    public void addTexto(String texto){
        if (texto == null) return;
        String t = texto.trim();
        if (t.isEmpty()) return;

        // Tokens especiales
        if ("DEL".equalsIgnoreCase(t)) {
            deleteLast();
            return;
        }
        if ("SPACE".equalsIgnoreCase(t)) {
            panelTexto.setText(panelTexto.getText().concat(" "));
            return;
        }
        if ("NOTHING".equalsIgnoreCase(t)) {
            return; // no escribir nada
        }

        // Por defecto añadir tal cual (letra u otro token válido)
        panelTexto.setText(panelTexto.getText().concat(t));
    }
    
    public void deleteLast(){
        String current = panelTexto.getText();
        if (current != null && !current.isEmpty()) {
            panelTexto.setText(current.substring(0, current.length()-1));
        }
    }
    
    public void setTexto(String texto){
        panelTexto.setText(texto);
    }
    
    public void clearTexto(){
        panelTexto.setText("");
    }
    
