    /**
     * Intenta invocar un método del ControllerUI con firma (JTextComponent).
     * Devuelve true si se invocó correctamente; en caso contrario, false.
     */
    private boolean tryInvokeController(String methodName) {
        if (controller == null) return false;
        try {
            Method m = controller.getClass().getMethod(methodName, javax.swing.text.JTextComponent.class);
            m.invoke(controller, panelTexto);
            return true;
        } catch (NoSuchMethodException e) {
            return false; // El ControllerUI aún no implementa la versión Swing
        } catch (Exception e) {
            // Cualquier otra incidencia: no romper la UI, usar fallback local
            return false;
        }
    }
